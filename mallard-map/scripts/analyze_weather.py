"""REAL-data analysis of what weather goes with mallard migration departures (USGS ND/SD juveniles, 2018-2020).

Run from mallard-map/:  python scripts/analyze_weather.py   ->  docs/kb/topics/weather-triggers-data.md + app data
Source: Pearse et al. 2023 data release (doi:10.5066/P9GSUQUU), files MALL_timing.csv and MALL_dist_dir.csv.
In MALL_timing.csv each bird-movement record is a run of daily rows; Move = 0 marks the day the bird moved
(n matches the 147 migration and 415 regional moves in MALL_dist_dir.csv), Move = 1 marks days it stayed.
"""
import json
from pathlib import Path
import numpy as np, pandas as pd

ROOT = Path(__file__).resolve().parents[1]
t = pd.read_csv(ROOT / "data/usgs/MALL_timing.csv")
d = pd.read_csv(ROOT / "data/usgs/MALL_dist_dir.csv")
m = t[t.Move_type == "M"]
ev, stay = m[m.Move == 0], m[m.Move == 1]
assert len(ev) == (d.Move_type == "M").sum(), "event coding changed"

rules = []
for label, col, thr, op in [("Overnight low -5 °C (23 °F) or colder", "Temp_min", -5, "le"),
                             ("Overnight low -10 °C (14 °F) or colder", "Temp_min", -10, "le"),
                             ("Overnight low -15 °C (5 °F) or colder", "Temp_min", -15, "le"),
                             ("Snow on the ground (1 cm or more)", "Snow_depth", 1, "ge"),
                             ("3-day weather severity index 10 or more", "WSI3", 10, "ge"),
                             ("Tailwind (wind index > 0)", "Wind_index", 0, "gt")]:
    f = {"le": lambda s: s <= thr, "ge": lambda s: s >= thr, "gt": lambda s: s > thr}[op]
    a, b = f(ev[col]).mean(), f(stay[col]).mean()
    rules.append({"label": label, "departDays": round(a * 100), "otherDays": round(b * 100), "ratio": round(a / b, 1) if b else None})

mig = d[d.Move_type == "M"]
slope = np.polyfit(mig.Temp_min, mig.Move_d, 1)[0]
r = np.corrcoef(mig.Temp_min, mig.Move_d)[0, 1]
reg = t[t.Move_type == "R"]
out = {"nDepartures": int(len(ev)), "nStayDays": int(len(stay)), "rules": rules,
       "medianDepart": ev[["Temp_min", "Snow_depth", "WSI3"]].median().round(1).to_dict(),
       "medianStay": stay[["Temp_min", "Snow_depth", "WSI3"]].median().round(1).to_dict(),
       "regionalWeatherDiff": bool(abs(reg[reg.Move == 0].Temp_min.median() - reg[reg.Move == 1].Temp_min.median()) > 1),
       "distSlopeKmPerC": round(float(slope), 1), "distR": round(float(r), 2)}
(ROOT.parent / "public/duck-map/data/weather.json").write_text(json.dumps(out))
md = ["# Weather on mallard departure days (REAL data, our analysis) — auto-generated by scripts/analyze_weather.py", "",
      f"Data: {out['nDepartures']} migration departures (moves > 310 km) vs {out['nStayDays']} days the same birds stayed; 97 juvenile",
      "mallards GPS/satellite-tagged in North and South Dakota, 2018–2020 (S2). Same latitude band as Montana's Hi-Line and east.", "",
      "| Condition | % of departure days | % of other days | Times more common on departure days |", "|---|---|---|---|"]
md += [f"| {x['label']} | {x['departDays']}% | {x['otherDays']}% | {x['ratio']}x |" for x in rules]
md += ["", f"Median on departure days: low {out['medianDepart']['Temp_min']} °C, snow {out['medianDepart']['Snow_depth']} cm, WSI3 {out['medianDepart']['WSI3']}.",
       f"Median on stay days: low {out['medianStay']['Temp_min']} °C, snow {out['medianStay']['Snow_depth']} cm, WSI3 {out['medianStay']['WSI3']}.",
       f"Short regional moves (25–310 km): weather on move days ≈ stay days (difference > 1 °C: {out['regionalWeatherDiff']}). Local shuffles are not weather-driven; long migrations are.",
       "", f"Distance vs cold, simple fit on the public table: {out['distSlopeKmPerC']} km per 1 °C warmer (r = {out['distR']}). The paper's",
       "multivariable model reports 166 km farther per 1 °C colder; our one-variable fit agrees on direction, not size. Use the paper's number with that caveat.",
       "", "Caveats: juveniles only; ND/SD weather stations; days are not independent (same birds). Descriptive, not a fitted model."]
(ROOT / "docs/kb/topics/weather-triggers-data.md").write_text("\n".join(md) + "\n")
print("\n".join(md))
